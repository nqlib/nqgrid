#!/usr/bin/env bash
# Regenerate src/nqgrid_export/models.py (Pydantic v2) from the nqgrid JSON Schemas and
# refresh the schema copies shipped inside the package. Run from anywhere:
#   integrations/python/scripts/generate_models.sh
# Needs datamodel-code-generator and ruff (pip install -e '.[dev]').
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
contract="$here/../../contract/pivot/v1"
pkg="$here/src/nqgrid_export"
bin="${VIRTUAL_ENV:-$here/.venv}/bin"
codegen="$bin/datamodel-codegen"
[[ -x "$codegen" ]] || codegen="datamodel-codegen"

mkdir -p "$pkg/schemas"
cp "$contract/pivot-spec.schema.json" "$contract/export-request.schema.json" "$contract/examples/planning.spec.json" "$pkg/schemas/"

# export-request.schema.json $refs pivot-spec.schema.json, so one run emits both models.
(
  cd "$pkg/schemas"
  PATH="$bin:$PATH" "$codegen" \
    --input export-request.schema.json \
    --input-file-type jsonschema \
    --output "$pkg/models.py" \
    --output-model-type pydantic_v2.BaseModel \
    --target-python-version 3.10 \
    --use-annotated \
    --field-constraints \
    --use-standard-collections \
    --use-union-operator \
    --use-double-quotes \
    --use-title-as-name \
    --use-schema-description \
    --use-field-description \
    --enum-field-as-literal all \
    --extra-fields forbid \
    --collapse-root-models \
    --disable-timestamp \
    --formatters ruff-format \
    --custom-file-header "# Generated by scripts/generate_models.sh from contract/pivot/v1/*.schema.json (datamodel-codegen). Do not edit."
)
echo "wrote $pkg/models.py"
